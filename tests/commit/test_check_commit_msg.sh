#!/bin/sh
# commit 스킬 검사기(skills/commit/scripts/check_commit_msg.sh) 회귀 테스트
# 사용법: 저장소 루트에서 sh tests/commit/test_check_commit_msg.sh
#         다른 셸로 돌리려면 SH=bash sh tests/commit/test_check_commit_msg.sh

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
CHECK="$ROOT/skills/commit/scripts/check_commit_msg.sh"
SH=${SH:-sh}
pass=0
fail=0

# 저장소에 .commit-msg-deny가 생겨도 기본 테스트 결과가 바뀌지 않게 빈 패턴 파일을 쓴다.
COMMIT_MSG_DENY_FILE=/dev/null
export COMMIT_MSG_DENY_FILE

# t <기대 종료 코드> <이름> <메시지(printf 형식)> [--title]
t() {
  exp=$1; name=$2; msg=$3; flag=${4:-}
  if [ -n "$flag" ]; then
    out=$(printf "$msg" | $SH "$CHECK" "$flag" - 2>&1); code=$?
  else
    out=$(printf "$msg" | $SH "$CHECK" - 2>&1); code=$?
  fi
  if [ "$code" -eq "$exp" ]; then
    pass=$((pass + 1)); printf 'ok   %s\n' "$name"
  else
    fail=$((fail + 1)); printf 'FAIL %s (기대 %s, 결과 %s)\n' "$name" "$exp" "$code"
    printf '%s\n' "$out" | sed 's/^/     /'
  fi
}

repeat() { awk -v s="$1" -v n="$2" 'BEGIN { for (i = 0; i < n; i++) printf "%s", s }'; }

# 통과해야 하는 메시지
t 0 "기본 헤더" 'feat(auth): 카카오 로그인 추가\n'
t 0 "본문, 이슈, 사람 공동 작업자, Assisted-by" 'fix(cart): 수량 0 주문 차단\n\n수량을 0으로 바꿔도 결제 버튼이 활성화돼 빈 주문이 생성됐다.\n\nCloses #87\nCo-authored-by: 홍길동 <hong@example.com>\nAssisted-by: Example Agent\n'
t 0 "사람의 GitHub noreply 주소는 허용" 'feat: 로그인 추가\n\nCo-authored-by: 홍길동 <12345+hong@users.noreply.github.com>\n'
t 0 "! 와 BREAKING CHANGE 함께" 'feat(api)!: 주문 조회 응답을 페이지 단위로 변경\n\n본문\n\nBREAKING CHANGE: GET /orders 응답 형식 변경\n'
t 0 "대문자 고유명사로 시작하는 한국어 제목" 'docs: README 설치 안내 갱신\n'
t 0 "본문의 평범한 generated by 문장" 'build: 코드 생성 단계 추가\n\nGenerated by the build script before compile.\n'
t 0 "헤더 72자" "feat: $(repeat 가 66)\n"

# 형식 위반
t 1 "대문자 type과 마침표" 'Feat: 로그인 수정.\n'
t 1 "허용되지 않은 type" 'feature: 로그인 추가\n'
t 1 "콜론 뒤 공백 없음" 'feat:로그인 추가\n'
t 1 "scope 대문자" 'feat(Auth): 로그인 추가\n'
t 1 "헤더 73자" "feat: $(repeat 가 67)\n"
t 1 "이모지 접두어" '✨ feat: 로그인 추가\n'
t 1 "제목 안의 이모지" 'feat: 🐛 로그인 버그 수정\n'
t 1 "기호 이모지와 변형 선택자" 'refactor: ♻️ 로그인 정리\n'
t 1 "대상 없는 제목" 'feat: 수정\n'
t 1 "헤더 다음 빈 줄 누락" 'feat(auth): 로그인 추가\n본문이 바로 붙음\n'
t 1 "! 만 있고 BREAKING CHANGE 없음" 'feat(api)!: 응답 변경\n\n본문\n'
t 1 "BREAKING CHANGE만 있고 ! 없음" 'feat(api): 응답 변경\n\nBREAKING CHANGE: 형식 변경\n'

# AI 도구의 자동 표기
t 1 "AI 공동 작성자(noreply 주소)" 'feat: 로그인 추가\n\nCo-authored-by: Example Agent <noreply@agent.example>\n'
t 1 "AI 공동 작성자([bot] 계정)" 'feat: 로그인 추가\n\nCo-authored-by: helper[bot] <1+helper[bot]@users.noreply.github.com>\n'
t 1 "세션 링크 트레일러" 'feat: 로그인 추가\n\nAgent-Session: https://agent.example/session/1\n'
t 1 "링크가 붙은 생성 표기" 'feat: 로그인 추가\n\nGenerated with [Example Agent](https://agent.example)\n'
t 1 "로봇 이모지로 시작하는 줄" 'feat: 로그인 추가\n\n🤖 자동 생성\n'

# git이 만드는 메시지와 입력 형태
t 0 "머지 메시지는 건너뜀" "Merge branch 'feature/login'\n"
t 0 "git revert 메시지는 건너뜀" 'Revert "feat(auth): 로그인 추가"\n\nThis reverts commit abc123.\n'
t 0 "fixup 커밋은 건너뜀" 'fixup! feat(auth): 로그인 추가\n'
t 0 "CRLF 줄바꿈" 'feat(auth): 로그인 추가\r\n\r\n본문\r\n'
t 0 "앞쪽 빈 줄과 주석" '\n\nfeat(auth): 로그인 추가\n# 주석 줄\n'
t 0 "verbose 구분선 아래는 무시" 'feat(auth): 로그인 추가\n\n본문\n# ------------------------ >8 ------------------------\ndiff --git a/x b/x\nCo-authored-by: X <noreply@agent.example>\n'
t 0 "본문 긴 줄은 경고만" "docs: 안내 갱신\n\n$(repeat 가 101)\n"
t 1 "빈 메시지" ''

# PR 제목 모드
t 0 "--title: ! 단독 허용" 'feat(api)!: 응답을 페이지 단위로 변경\n' --title
t 1 "--title: 형식 위반" 'Update README\n' --title

# 저장소 추가 패턴(.commit-msg-deny)
deny=$(mktemp)
printf '# 예: 특정 도구가 붙이는 공동 작성자\n^Co-authored-by: Tool Bot\n\n' > "$deny"
COMMIT_MSG_DENY_FILE=$deny
t 1 "추가 패턴에 걸림" 'feat: 로그인 추가\n\nCo-authored-by: Tool Bot <bot@tool.example>\n'
t 0 "추가 패턴에 안 걸리면 통과" 'feat: 로그인 추가\n\nCo-authored-by: 홍길동 <hong@example.com>\n'
COMMIT_MSG_DENY_FILE=/dev/null
rm -f "$deny"

printf '\n통과 %s, 실패 %s\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
